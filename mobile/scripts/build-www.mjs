// Builds mobile/www from the citizen portal in ../frontend — the same HTML, CSS and JavaScript as the
// website, so the app looks and behaves exactly like the citizen portal. Only three things differ:
//   * index.html is an app sign-in screen (citizen accounts only) with a server-address setting;
//   * Leaflet and the Plus Jakarta Sans font are bundled instead of loaded from a CDN;
//   * js/app-shell.js is added to every page (citizen-only guard, offline notice).
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const MOBILE = join(here, '..');
const FRONT = join(MOBILE, '..', 'frontend');
const WWW = join(MOBILE, 'www');
const NM = join(MOBILE, 'node_modules');

const PAGES = ['citizen.html', 'map.html', 'incident.html'];
const SCRIPTS = ['api.js', 'common.js', 'i18n.js', 'voice-recorder.js', 'citizen.js', 'map.js', 'utility-network.js', 'incident.js'];

rmSync(WWW, { recursive: true, force: true });
mkdirSync(join(WWW, 'js'), { recursive: true });
cpSync(join(FRONT, 'css'), join(WWW, 'css'), { recursive: true });
cpSync(join(FRONT, 'assets'), join(WWW, 'assets'), { recursive: true });
for (const s of SCRIPTS) cpSync(join(FRONT, 'js', s), join(WWW, 'js', s));
for (const f of readdirSync(join(MOBILE, 'app'))) {
  cpSync(join(MOBILE, 'app', f), join(WWW, f.endsWith('.js') ? join('js', f) : f));
}

// Bundled libraries (no CDN needed inside the app)
cpSync(join(NM, 'leaflet', 'dist'), join(WWW, 'vendor', 'leaflet'), { recursive: true });
const fontDir = join(NM, '@fontsource', 'plus-jakarta-sans');
cpSync(join(fontDir, 'files'), join(WWW, 'vendor', 'fonts', 'files'), { recursive: true });
writeFileSync(join(WWW, 'vendor', 'fonts', 'jakarta.css'),
  ['400', '600', '700', '800'].map(w => readFileSync(join(fontDir, `${w}.css`), 'utf8')).join('\n'));

const FONT_LINKS = /<link rel="preconnect" href="https:\/\/fonts\.googleapis\.com"\/>\s*<link href="https:\/\/fonts\.googleapis\.com\/css2[^"]*" rel="stylesheet"\/>/;
for (const page of PAGES) {
  let html = readFileSync(join(FRONT, page), 'utf8');
  const before = html;
  html = html.replace(FONT_LINKS, '<link rel="stylesheet" href="vendor/fonts/jakarta.css"/>')
    .replaceAll('https://unpkg.com/leaflet@1.9.4/dist/', 'vendor/leaflet/')
    .replace('<script src="js/api.js"></script>', '<script src="js/api.js"></script>\n<script src="js/app-shell.js"></script>')
    .replace('<link rel="stylesheet" href="css/style.css"/>', '<link rel="stylesheet" href="css/style.css"/>\n<link rel="stylesheet" href="app.css"/>')
    .replace('<meta name="viewport" content="width=device-width, initial-scale=1.0"/>',
             '<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover"/>');
  if (html === before || !html.includes('js/app-shell.js')) throw new Error(`Could not adapt ${page}`);
  if (/https:\/\/unpkg\.com|fonts\.googleapis/.test(html)) throw new Error(`${page} still loads a CDN resource`);
  writeFileSync(join(WWW, page), html);
}
if (!existsSync(join(WWW, 'index.html'))) throw new Error('app/index.html missing');

// Default server address suggested on first launch (users can change it in the app).
// Set CIVICMIND_APP_SERVER=https://your-civicmind-server when building a release for your deployment.
const server = (process.env.CIVICMIND_APP_SERVER || '').trim().replace(/\/+$/, '');
if (server && !/^https?:\/\/[^\s"'<>]+$/.test(server)) throw new Error('CIVICMIND_APP_SERVER must be an http(s) URL');
writeFileSync(join(WWW, 'js', 'app-config.js'),
  `/* generated by scripts/build-www.mjs */\nwindow.CM_APP = ${JSON.stringify({ defaultServer: server, version: process.env.npm_package_version || '1.0.0' })};\n`);

// Officer/admin pages are not part of the app: if the server ever sends a non-citizen there, sign out.
const stub = `<!DOCTYPE html><meta charset="UTF-8"><title>CivicMind</title><script>
try { localStorage.removeItem('cm_token'); localStorage.removeItem('cm_user'); } catch (e) {}
location.replace('index.html?role=1');</script>`;
for (const page of ['dashboard.html', 'admin.html', 'assets.html', 'data-sources.html']) writeFileSync(join(WWW, page), stub);
console.log(`www built: ${PAGES.length} citizen pages + app sign-in, ${SCRIPTS.length} shared scripts, bundled Leaflet and fonts`);
